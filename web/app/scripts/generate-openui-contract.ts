import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { library as dashboardLibrary, promptOptions as dashboardPromptOptions } from "@openuidev/dashboard-library";
import { openUIComponentGroups } from "@prime-agent/web-protocol/openui-component-groups";
import { openUILibrary } from "@/components/openui/openui-library";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const signaturesPath = resolve(appRoot, "../server/src/openui-signatures.ts");
const dashboardSpecPath = resolve(appRoot, "../server/src/dashboards/library-spec.json");

const librarySpec = openUILibrary.toSpec() as ReturnType<typeof openUILibrary.toSpec> & { schema?: unknown };
const { componentGroups: _libraryGroups, schema: _librarySchema, ...specWithoutGroups } = librarySpec;
if (JSON.stringify(_libraryGroups) !== JSON.stringify(openUIComponentGroups)) {
	throw new Error("OpenUI library componentGroups drifted from openui-component-groups.ts.");
}

const rawSignaturesSource = `// @generated by web/app/scripts/generate-openui-contract.ts — do not edit

import type { PromptSpec } from "@openuidev/lang-core";
import { openUIComponentGroups } from "@prime-agent/web-protocol/openui-component-groups";

const generatedOpenUIPromptSpec = ${JSON.stringify(specWithoutGroups, null, "\t")};

export const openUIPromptSpec: PromptSpec = {
	...generatedOpenUIPromptSpec,
	componentGroups: openUIComponentGroups,
};
`;
const dashboardSpecSource = `${JSON.stringify({
	spec: dashboardLibrary.toSpec(),
	promptOptions: {
		preamble: dashboardPromptOptions.preamble,
		examples: dashboardPromptOptions.examples,
		additionalRules: dashboardPromptOptions.additionalRules,
	},
})}\n`;

function format(source: string, path: string): string {
	const oxfmt = resolve(appRoot, "../../node_modules/oxfmt/bin/oxfmt");
	const result = spawnSync(process.execPath, [oxfmt, "--stdin-filepath", path], {
		input: source,
		encoding: "utf8",
	});
	if (result.status !== 0) throw new Error(result.stderr || `Oxfmt formatting failed for ${path}`);
	return result.stdout;
}

const signaturesSource = format(rawSignaturesSource, signaturesPath);

async function check(path: string, expected: string): Promise<boolean> {
	return (await readFile(path, "utf8").catch(() => "")) === expected;
}

if (process.argv.includes("--check")) {
	const fresh =
		(await check(signaturesPath, signaturesSource)) && (await check(dashboardSpecPath, dashboardSpecSource));
	if (!fresh) {
		throw new Error("OpenUI generated contract is stale. Run pnpm --filter @qredence/web generate:openui-contract");
	}
} else {
	await writeFile(signaturesPath, signaturesSource, "utf8");
	await writeFile(dashboardSpecPath, dashboardSpecSource, "utf8");
}
