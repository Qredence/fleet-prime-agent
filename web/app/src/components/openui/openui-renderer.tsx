import type { ActionEvent, OpenUIError, ParseResult } from "@openuidev/react-lang";
import { BuiltinActionType, Renderer } from "@openuidev/react-lang";
import { OpenPanelActionSchema } from "@prime-agent/web-protocol/fleet-contract";
import { useCallback, useEffect, useMemo, useState } from "react";
import { Markdown } from "@/components/chat/markdown/markdown";
import { UiErrorBoundary } from "@/components/layout/ui-error-boundary";
import { type OpenUIArtifactCandidate, OpenUIArtifactProvider } from "@/components/openui/html-artifact";
import {
	encodeOpenPanelActionMessage,
	OPEN_PANEL_ACTION_NAME,
	openPanelActionFromParams,
} from "@/components/openui/open-panel-action-message";
import { openUILibrary } from "@/components/openui/openui-library";
import { buildOpenUIRepairRequest, toRepairableErrors } from "@/components/openui/openui-repair";
import { readStoredState, writeStoredState } from "@/components/openui/openui-state-store";
import { openUIToolProvider } from "@/components/openui/openui-tools";
import { segmentOpenUIContent } from "@/components/openui/openui-utils";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";

type OpenUIStateByBlock = Record<string, Record<string, unknown>>;

function getActionMessage(event: ActionEvent) {
	if (event.type === BuiltinActionType.OpenUrl) return null;

	if (event.type === "fleet.open_panel") {
		const action = OpenPanelActionSchema.safeParse(event.params);
		return action.success ? encodeOpenPanelActionMessage(action.data) : null;
	}

	// Library-defined `@OpenPanel(...)` step: params are schema-checked before
	// they reach the panel layer, same as the positional component form.
	if (event.type === OPEN_PANEL_ACTION_NAME) {
		const action = openPanelActionFromParams(event.params);
		return action ? encodeOpenPanelActionMessage(action) : null;
	}

	if (event.type === BuiltinActionType.ContinueConversation) {
		const message = event.params.message;
		if (typeof message === "string" && message.trim()) return message;
	}

	return event.humanFriendlyMessage.trim() || null;
}

function getFinalErrors(result: ParseResult | null, isStreaming?: boolean) {
	if (!result || isStreaming) return [];

	const unresolvedErrors = result.meta.unresolved.map((ref) => ({
		code: "unresolved-reference",
		message: `Reference "${ref}" was used but never defined.`,
		source: "parser",
	}));

	return [...result.meta.errors, ...unresolvedErrors];
}

function OpenUIDiagnostics({ errors, onRepair, raw }: { errors: Array<unknown>; onRepair?: () => void; raw: string }) {
	if (errors.length === 0) return null;

	const messages = errors
		.map((error) => {
			if (typeof error === "object" && error !== null && "message" in error && typeof error.message === "string") {
				return error.message;
			}

			return null;
		})
		.filter((message): message is string => Boolean(message));

	const summary = messages[0] ?? "OpenUI output could not be rendered.";

	return (
		<Alert variant="destructive" className="mt-4 w-full">
			<AlertTitle>OpenUI could not be rendered</AlertTitle>
			<AlertDescription>
				<p className="mb-3 leading-relaxed">The generated UI could not be rendered. {summary}</p>
				<details className="border-t border-destructive/30 pt-3">
					<summary className="cursor-pointer font-semibold">Technical details</summary>
					<pre className="mt-3 mb-4 font-mono whitespace-pre-wrap">{JSON.stringify(errors, null, 2)}</pre>
					<div className="border-t border-destructive/30 pt-4">
						<h5 className="mb-2 font-bold">Raw output generated by AI:</h5>
						<pre className="font-mono whitespace-pre-wrap">{raw}</pre>
					</div>
				</details>
				{onRepair ? (
					<Button type="button" size="compact" variant="outline" className="mt-3" onClick={onRepair}>
						Repair UI
					</Button>
				) : null}
			</AlertDescription>
		</Alert>
	);
}

/** Renders an OpenUI block while coordinating actions, artifacts, state updates, and diagnostics. */
function OpenUIBlock({
	blockId,
	content,
	initialState,
	isStreaming,
	messageId,
	onAction,
	onArtifactReady,
	onOpenArtifact,
	onStateUpdate,
}: {
	blockId: string;
	messageId?: string;
	content: string;
	initialState?: Record<string, unknown>;
	isStreaming?: boolean;
	onAction?: (message: string) => void;
	onArtifactReady?: (candidate: OpenUIArtifactCandidate) => void | Promise<string | undefined>;
	onOpenArtifact?: (artifactId: string) => void;
	onStateUpdate: (blockId: string, state: Record<string, unknown>) => void;
}) {
	const [runtimeErrors, setRuntimeErrors] = useState<Array<OpenUIError>>([]);
	const [parseResult, setParseResult] = useState<ParseResult | null>(null);

	const handleError = useCallback((nextErrors: Array<OpenUIError>) => {
		if (nextErrors.length > 0) {
			console.warn("OpenUI parsing/validation errors:", nextErrors);
		}

		setTimeout(() => {
			setRuntimeErrors((previousErrors) =>
				JSON.stringify(previousErrors) === JSON.stringify(nextErrors) ? previousErrors : nextErrors,
			);
		}, 0);
	}, []);

	const handleAction = useCallback(
		(event: ActionEvent) => {
			const message = getActionMessage(event);
			if (message) onAction?.(message);
		},
		[onAction],
	);

	const artifactProviderValue = useMemo(
		() => ({
			messageId,
			artifactIndex: 0,
			onArtifactReady,
			onOpenArtifact,
		}),
		[messageId, onArtifactReady, onOpenArtifact],
	);

	const finalErrors = getFinalErrors(parseResult, isStreaming);
	const allErrors = useMemo(() => [...runtimeErrors, ...finalErrors], [runtimeErrors, finalErrors]);
	const repairRequest = useMemo(() => buildOpenUIRepairRequest(toRepairableErrors(allErrors)), [allErrors]);

	return (
		<div className="flex w-full flex-col gap-2">
			<UiErrorBoundary resetKeys={[content]}>
				<OpenUIArtifactProvider value={artifactProviderValue}>
					<Renderer
						initialState={initialState}
						isStreaming={isStreaming}
						library={openUILibrary}
						response={content}
						toolProvider={openUIToolProvider}
						onAction={handleAction}
						onError={handleError}
						onParseResult={setParseResult}
						onStateUpdate={(state) => onStateUpdate(blockId, state)}
					/>
				</OpenUIArtifactProvider>
			</UiErrorBoundary>
			<OpenUIDiagnostics
				errors={allErrors}
				onRepair={onAction && repairRequest ? () => onAction(repairRequest) : undefined}
				raw={content}
			/>
		</div>
	);
}

export function GenerativeTextRenderer({
	content,
	className,
	isStreaming,
	messageId,
	onOpenUIAction,
	onOpenUIArtifactReady,
	onOpenArtifact,
}: {
	content: string;
	className?: string;
	isStreaming?: boolean;
	messageId?: string;
	onOpenUIAction?: (message: string) => void;
	onOpenUIArtifactReady?: (candidate: OpenUIArtifactCandidate) => void | Promise<string | undefined>;
	onOpenArtifact?: (artifactId: string) => void;
}) {
	const [stateByBlock, setStateByBlock] = useState<OpenUIStateByBlock>({});
	const segments = useMemo(() => segmentOpenUIContent(content), [content]);
	const sessionKey = messageId ?? "message";

	const updateBlockState = useCallback(
		(blockId: string, state: Record<string, unknown>) => {
			setStateByBlock((previous) => ({ ...previous, [blockId]: state }));
			const segment = segments.find((candidate) => `${sessionKey}:${candidate.id}` === blockId);
			// Persist per block so a reload restores what the user selected.
			if (segment) writeStoredState(sessionKey, segment.id, segment.content, state);
		},
		[segments, sessionKey],
	);

	// Hydrate stored form state once per block, before the renderer mounts.
	useEffect(() => {
		if (segments.length === 0) return;
		setStateByBlock((previous) => {
			let changed = false;
			const next = { ...previous };
			for (const segment of segments) {
				if (segment.type !== "openui") continue;
				const blockId = `${sessionKey}:${segment.id}`;
				if (next[blockId] !== undefined) continue;
				const stored = readStoredState(sessionKey, segment.id);
				if (stored) {
					next[blockId] = stored;
					changed = true;
				}
			}
			// Returning `previous` keeps the effect from re-rendering on no-op runs.
			return changed ? next : previous;
		});
	}, [segments, sessionKey]);

	if (segments.length === 1 && segments[0]?.type === "markdown") {
		return <Markdown className={className} content={content} isStreaming={isStreaming} />;
	}

	return (
		<div className={`flex w-full flex-col gap-3 ${className ?? ""}`}>
			{segments.map((segment) => {
				if (segment.type === "markdown") {
					return (
						<Markdown
							key={segment.id}
							content={segment.content}
							className="leading-relaxed [&_p]:leading-relaxed"
							isStreaming={isStreaming}
						/>
					);
				}

				const blockId = `${messageId ?? "message"}:${segment.id}`;

				return (
					<OpenUIBlock
						key={blockId}
						blockId={blockId}
						messageId={messageId}
						content={segment.content}
						initialState={stateByBlock[blockId]}
						isStreaming={isStreaming}
						onAction={onOpenUIAction}
						onArtifactReady={onOpenUIArtifactReady}
						onOpenArtifact={onOpenArtifact}
						onStateUpdate={updateBlockState}
					/>
				);
			})}
		</div>
	);
}
