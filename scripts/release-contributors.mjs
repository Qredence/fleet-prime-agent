#!/usr/bin/env node

// Credits the people behind a Fleet release.
//
// The contributors of a release are the human authors of the pull requests merged into main since
// the previous release tag. They are derived from GitHub rather than hand-maintained, like the rest
// of the release notes: the GitHub release body lists them with their pull requests, and the
// release pull request folds any new name into the README's Contributors list, so neither can drift
// from the history they describe.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const readmePath = fileURLToPath(new URL("../README.md", import.meta.url));
const baseBranch = "main";
const releaseBranchPrefix = "release/fleet-";
// Bounds the per-commit pull request lookups so a large release cannot exhaust the API budget.
const lookupConcurrency = 5;

export const README_CONTRIBUTORS_START = "<!-- contributors:start -->";
export const README_CONTRIBUTORS_END = "<!-- contributors:end -->";

// Automation and AI identities that author or co-author pull requests and commits here but are not
// people. Accounts GitHub marks as bots (type `Bot`, or a `[bot]` login) are excluded without being
// listed.
const NON_HUMAN_LOGINS = new Set([
	"amp",
	"ampagent",
	"claude",
	"codex",
	"coderabbit",
	"coderabbitai",
	"commandcodebot",
	"copilot",
	"cursor",
	"cursoragent",
	"dependabot",
	"devin-ai-integration",
	"gitar",
	"gitar-bot",
	"github-actions",
	"oz-agent",
	"renovate",
]);

// GitHub logins: alphanumerics and single inner hyphens, at most 39 characters.
const LOGIN_PATTERN = /^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$/;

/**
 * Decides whether a GitHub account belongs to a person.
 * @param {{login?: string, type?: string}|null|undefined} user - The account as returned by the GitHub API.
 * @returns {boolean} `true` for a person's account, `false` for bots, automation, AI agents, and malformed logins.
 */
export function isHumanContributor(user) {
	const login = user?.login;
	if (typeof login !== "string" || !LOGIN_PATTERN.test(login)) return false;
	if (user.type && user.type !== "User") return false;
	return !NON_HUMAN_LOGINS.has(login.toLowerCase());
}

/**
 * Groups merged pull requests by their human authors.
 *
 * Release pull requests are skipped: they are generated by the release automation under whichever
 * account owns its token, and crediting that account for every release would say nothing.
 * @param {Array<object>} pullRequests - Pull requests as returned by the GitHub API, in any order and possibly repeated.
 * @returns {Array<{login: string, pullRequests: number[]}>} Contributors ordered by their first pull request, each with ascending pull request numbers.
 */
export function contributorsFromPullRequests(pullRequests) {
	const seen = new Set();
	const byLogin = new Map();
	for (const pullRequest of pullRequests ?? []) {
		const number = pullRequest?.number;
		if (!Number.isInteger(number) || seen.has(number)) continue;
		if (!pullRequest.merged_at || pullRequest.base?.ref !== baseBranch) continue;
		if (pullRequest.head?.ref?.startsWith(releaseBranchPrefix)) continue;
		if (!isHumanContributor(pullRequest.user)) continue;
		seen.add(number);
		const key = pullRequest.user.login.toLowerCase();
		const entry = byLogin.get(key) ?? { login: pullRequest.user.login, pullRequests: [] };
		entry.pullRequests.push(number);
		byLogin.set(key, entry);
	}
	const contributors = [...byLogin.values()];
	for (const contributor of contributors) contributor.pullRequests.sort((left, right) => left - right);
	return contributors.sort(
		(left, right) =>
			left.pullRequests[0] - right.pullRequests[0] ||
			left.login.toLowerCase().localeCompare(right.login.toLowerCase()),
	);
}

/**
 * Renders the Contributors section of a GitHub release body.
 * @param {Array<{login: string, pullRequests: number[]}>} contributors - The release's contributors.
 * @returns {string|undefined} The Markdown section, or `undefined` when there is nobody to credit.
 */
export function contributorsSection(contributors) {
	if (!contributors?.length) return undefined;
	return [
		"## Contributors",
		"",
		...contributors.map(
			({ login, pullRequests }) => `- @${login} (${pullRequests.map((number) => `#${number}`).join(", ")})`,
		),
	].join("\n");
}

/**
 * Reads the logins listed between the README's Contributors markers.
 * @param {string} readme - The README contents.
 * @returns {string[]} The listed logins, in file order.
 * @throws {Error} If the markers are missing or out of order.
 */
export function readmeContributors(readme) {
	const { body } = contributorsBlock(readme);
	return [...body.matchAll(/^- \[@([A-Za-z0-9-]+)\]/gm)].map((match) => match[1]);
}

/**
 * Locates the generated Contributors list in the README.
 * @param {string} readme - The README contents.
 * @returns {{before: string, body: string, after: string}} The text around and between the markers.
 * @throws {Error} If the markers are missing or out of order.
 */
function contributorsBlock(readme) {
	const start = readme.indexOf(README_CONTRIBUTORS_START);
	const end = readme.indexOf(README_CONTRIBUTORS_END);
	if (start === -1 || end === -1 || end < start) {
		throw new Error(
			`README.md has no ${README_CONTRIBUTORS_START} ... ${README_CONTRIBUTORS_END} block for the contributors list`,
		);
	}
	return {
		before: readme.slice(0, start + README_CONTRIBUTORS_START.length),
		body: readme.slice(start + README_CONTRIBUTORS_START.length, end),
		after: readme.slice(end),
	};
}

/**
 * Adds contributors to the README's Contributors list.
 *
 * The list only grows: everyone already credited stays, a login is never listed twice whatever its
 * case, and the list is kept in case-insensitive alphabetical order so additions produce small,
 * predictable diffs.
 * @param {string} readme - The README contents.
 * @param {string[]} logins - Logins to credit.
 * @returns {string} The README with the merged list.
 * @throws {Error} If the README has no Contributors markers.
 */
export function mergeReadmeContributors(readme, logins) {
	const { before, after } = contributorsBlock(readme);
	const byKey = new Map();
	for (const login of [...readmeContributors(readme), ...logins]) {
		if (!isHumanContributor({ login })) continue;
		const key = login.toLowerCase();
		if (!byKey.has(key)) byKey.set(key, login);
	}
	const lines = [...byKey.values()]
		.sort((left, right) => left.toLowerCase().localeCompare(right.toLowerCase()))
		.map((login) => `- [@${login}](https://github.com/${login})`);
	return `${before}\n${lines.join("\n")}\n${after}`;
}

/**
 * Lists the merged pull requests that introduced the commits between two refs.
 * @param {object} options - The comparison and its request dependency.
 * @param {string} options.owner - Repository owner.
 * @param {string} options.repo - Repository name.
 * @param {string} options.base - The earlier ref, normally the previous release tag.
 * @param {string} options.head - The later ref or commit.
 * @param {(path: string) => Promise<unknown>} options.request - Performs an authenticated GitHub GET and returns the parsed body.
 * @returns {Promise<Array<object>>} The associated pull requests, possibly repeated.
 */
export async function pullRequestsBetween({ owner, repo, base, head, request }) {
	const shas = [];
	for (let page = 1; ; page += 1) {
		const comparison = await request(
			`/repos/${owner}/${repo}/compare/${encodeURIComponent(base)}...${encodeURIComponent(head)}?per_page=100&page=${page}`,
		);
		const commits = Array.isArray(comparison?.commits) ? comparison.commits : [];
		shas.push(...commits.map((commit) => commit.sha).filter(Boolean));
		if (commits.length < 100 || shas.length >= (comparison?.total_commits ?? 0)) break;
	}
	const pullRequests = [];
	for (let index = 0; index < shas.length; index += lookupConcurrency) {
		const batch = await Promise.all(
			shas
				.slice(index, index + lookupConcurrency)
				.map((sha) => request(`/repos/${owner}/${repo}/commits/${sha}/pulls?per_page=100`)),
		);
		for (const associated of batch) if (Array.isArray(associated)) pullRequests.push(...associated);
	}
	return pullRequests;
}

/**
 * Collects the human contributors of the pull requests merged between two refs.
 * @param {Parameters<typeof pullRequestsBetween>[0]} options - The comparison and its request dependency.
 * @returns {Promise<Array<{login: string, pullRequests: number[]}>>} The contributors.
 */
export async function collectContributors(options) {
	return contributorsFromPullRequests(await pullRequestsBetween(options));
}

/**
 * Folds a release's contributors into the README on disk.
 * @param {Array<{login: string}>} contributors - The release's contributors.
 * @param {{path?: string}} [options] - The README location, overridable for tests.
 * @returns {boolean} `true` when the README changed.
 */
export function writeReadmeContributors(contributors, { path = readmePath } = {}) {
	const readme = readFileSync(path, "utf8");
	const updated = mergeReadmeContributors(
		readme,
		contributors.map(({ login }) => login),
	);
	if (updated === readme) return false;
	writeFileSync(path, updated, "utf8");
	return true;
}
